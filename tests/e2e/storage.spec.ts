import {test,expect,_electron,type ElectronApplication} from '@playwright/test';
import {mkdtemp,mkdir,copyFile,readdir} from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import Database from 'better-sqlite3';
let app:ElectronApplication;
test('Согласованная копия WAL, восстановление на копии и миграция v0 → v1',async()=>{
  const root=await mkdtemp(path.join(os.tmpdir(),'FireCNC-storage-'));
  const env=(directory:string):Record<string,string>=>Object.fromEntries(Object.entries({...process.env,FCNC_DATA_DIR:directory}).filter(([k,v])=>v!==undefined&&k!=='ELECTRON_RUN_AS_NODE')) as Record<string,string>;
  const launch=async(directory:string)=>{app=await _electron.launch({args:['.',...(process.platform==='linux'?['--ozone-platform=x11']:[])],env:env(directory),chromiumSandbox:true});const page=await app.firstWindow();await expect(page.getByRole('heading',{name:'От понимания — к обработке'})).toBeVisible();return page;};
  const original=path.join(root,'original'),restored=path.join(root,'restored'),legacy=path.join(root,'legacy');
  let page=await launch(original);
  expect((await page.evaluate(()=>window.academy.profile('Сохранённый профиль'))).ok).toBe(true);
  expect((await page.evaluate(()=>window.academy.lessonComplete('turning-axes'))).ok).toBe(true);
  const backupFile=path.join(root,'consistent.sqlite');
  await app.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},backupFile);
  expect((await page.evaluate(()=>window.academy.backup())).ok).toBe(true);
  await mkdir(legacy);
  const db=new Database(backupFile,{readonly:true});const integrity=db.pragma('quick_check',{simple:true});db.close();
  const old=new Database(path.join(legacy,'academy.sqlite'));old.exec("CREATE TABLE settings(key TEXT PRIMARY KEY,value TEXT NOT NULL); INSERT INTO settings VALUES ('sentinel','keep-me'); PRAGMA user_version=0;");old.close();
  expect(integrity).toBe('ok');await app.close();
  await mkdir(restored);await copyFile(backupFile,path.join(restored,'academy.sqlite'));
  page=await launch(restored);const state=await page.evaluate(()=>window.academy.state());
  expect(state.ok&&state.value.profile.name).toBe('Сохранённый профиль');expect(state.ok&&state.value.completed).toContain('turning-axes');await app.close();
  await launch(legacy);
  const files=await readdir(legacy);expect(files.some(f=>f.startsWith('before-migration-'))).toBe(true);
  const migratedDB=new Database(path.join(legacy,'academy.sqlite'),{readonly:true});const migrated={version:migratedDB.pragma('user_version',{simple:true}),sentinel:migratedDB.prepare("SELECT value FROM settings WHERE key='sentinel'").get()};migratedDB.close();
  expect(migrated).toEqual({version:1,sentinel:{value:'keep-me'}});await app.close();
});
test.afterEach(async({},info)=>{if(info.status!=='passed')app?.process().kill();else await app?.close().catch(()=>{});});
