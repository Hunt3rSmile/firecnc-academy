import {test,expect,_electron,type ElectronApplication} from '@playwright/test';
import {mkdtemp,readFile,stat} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {issueLicense} from '../../tools/license-issuer/src/issuer';
let app:ElectronApplication;
test('IPC, аварии, 2D, откат воспроизведения, экспорт и узкие экраны',async()=>{
  const data=await mkdtemp(path.join(os.tmpdir(),'FireCNC-validation-'));
  const env:Record<string,string>={...(Object.fromEntries(Object.entries(process.env).filter(([,v])=>v!==undefined)) as Record<string,string>),FCNC_DATA_DIR:data};delete env.ELECTRON_RUN_AS_NODE;
  app=await _electron.launch({args:['.',...(process.platform==='linux'?['--ozone-platform=x11']:[])],env,chromiumSandbox:true});const page=await app.firstWindow();
  page.on('dialog',d=>void d.accept().catch(()=>{}));
  await page.setViewportSize({width:1366,height:768});
  await expect(page.getByRole('heading',{name:'От понимания — к обработке'})).toBeVisible();
  await app.evaluate(({dialog})=>{dialog.showMessageBoxSync=()=>1;});
  const sandbox=await page.evaluate(()=>window.academy.security);
  expect(sandbox.sandbox).toBe(true);expect(sandbox.contextIsolation).toBe(true);
  expect(await page.evaluate(()=>typeof (window as unknown as Record<string,unknown>).require)).toBe('undefined');
  const invalid=await page.evaluate(()=>window.academy.settings({theme:'dark',split:1000}));expect(invalid.ok).toBe(false);
  const unauthorized=await page.evaluate(()=>window.academy.authorizeSimulation({version:1,kind:'turning',name:'Свой проект',source:'G0 X20',offset:{x:0,y:0,z:0},resolution:.25}));expect(unauthorized.ok).toBe(false);
  const pem=await readFile('.local/issuer-private.pem','utf8');
  const token=issueLicense(pem,{edition:'student',modules:['theory','turning'],customer:'Проверка модулей',days:1}).token;
  const imported=await page.evaluate(t=>window.academy.licenseImport(t),token);expect(imported.ok).toBe(true);
  await page.reload();
  const forbidden=await page.evaluate(()=>window.academy.authorizeSimulation({version:1,kind:'milling',name:'Фреза',source:'G0 X20',offset:{x:0,y:0,z:0},resolution:.25}));expect(forbidden.ok).toBe(false);
  await page.getByRole('button',{name:'Редактор и симулятор',exact:true}).click();
  const editor=page.locator('.monaco-editor textarea').first();
  await page.locator('.monaco-editor .view-lines').click({position:{x:50,y:20}});await page.keyboard.press('ControlOrMeta+A');await page.keyboard.type('T0101\nS800 M3\nG0 X30 Z-10\nM30');
  await page.getByRole('button',{name:'▷ Рассчитать',exact:true}).click();
  await expect(page.getByText('Быстрый ход G0 входит в материал.',{exact:false})).toBeVisible();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'test-results/collision.png',fullPage:true});
  await page.locator('.monaco-editor .view-lines').click({position:{x:50,y:20}});await page.keyboard.press('ControlOrMeta+A');await page.keyboard.type('G0 X10\nG81 Z-5');
  await page.getByRole('button',{name:'▷ Рассчитать',exact:true}).click();
  await expect(page.getByText('G81 не поддерживается',{exact:false})).toBeVisible();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'test-results/program-error.png',fullPage:true});
  await page.getByRole('button',{name:'Точение',exact:true}).click();
  await page.getByRole('button',{name:'2D',exact:true}).click();
  await page.getByRole('button',{name:'▷ Рассчитать',exact:true}).click();
  await expect(page.getByText('Программа выполнена.',{exact:false})).toBeVisible();
  await page.getByRole('button',{name:'Измерить',exact:true}).click();
  await expect(page.getByText('Ø на Z−15: 30.00 мм',{exact:false})).toBeVisible();
  await page.getByRole('button',{name:'↺ Сброс',exact:true}).click();
  await expect(page.getByText('Выполнено кадров: 0.',{exact:false})).toBeVisible();
  await page.getByRole('button',{name:'Измерить',exact:true}).click();
  await expect(page.getByText('Ø на Z−15: 40.00 мм',{exact:false})).toBeVisible();
  await page.getByRole('button',{name:'Кадр →',exact:true}).click();
  await expect(page.getByText('Выполнено кадров: 1.',{exact:false})).toBeVisible();
  for(const [width,height] of [[1093,614],[911,512]] as const) {
    await page.setViewportSize({width,height});
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
    expect(overflow).toBe(false);
    await page.getByRole('button',{name:'Программа',exact:true}).click();await expect(editor).toBeVisible();
    await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:`test-results/simulator-${width}.png`,fullPage:true});
    await page.getByRole('button',{name:'Модель',exact:true}).click();
  }
  await page.setViewportSize({width:1366,height:768});
  await page.getByRole('button',{name:'Настройки и лицензия',exact:true}).click();
  const backupPath=path.join(data,'Согласованная-копия.sqlite');
  await app.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},backupPath);
  const backup=await page.evaluate(()=>window.academy.backup());expect(backup.ok&&backup.value).toBe(true);expect((await stat(backupPath)).size).toBeGreaterThan(0);
  const initial=await page.evaluate(()=>window.academy.state());
  await app.evaluate(()=>{const original=Date.now;Date.now=()=>original()+3600*1000;});
  expect((await page.evaluate(()=>window.academy.state())).ok).toBe(true);
  await app.evaluate(()=>{const ahead=Date.now;Date.now=()=>ahead()-3600*1000;});
  const rollback=await page.evaluate(()=>window.academy.state());expect(rollback.ok&&rollback.value.license.status).toBe('clock');
  await app.evaluate(()=>{const original=Date.now;Date.now=()=>original()+2*86400*1000;});
  const expired=await page.evaluate(()=>window.academy.state());expect(expired.ok&&expired.value.license.status).toBe('expired');
  await page.reload();await page.getByRole('button',{name:'Настройки и лицензия',exact:true}).click();
  await expect(page.getByText('Лицензия истекла.',{exact:false})).toBeVisible();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'test-results/license-expired.png',fullPage:true});
  const exportPath=path.join(data,'Результаты.json');
  await app.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},exportPath);
  expect((await page.evaluate(()=>window.academy.exportResults())).ok).toBe(true);
  const exported=JSON.parse(await readFile(exportPath,'utf8')) as {profile:{id:string}};
  expect(initial.ok&&exported.profile.id).toBe(initial.ok&&initial.value.profile.id);
  const blocked=await page.evaluate(()=>window.academy.lessonComplete('turning-feed'));expect(blocked.ok).toBe(false);
  await app.close();
});
test.afterEach(async({},info)=>{if(info.status!=='passed')app?.process().kill();else await app?.close().catch(()=>{});});
