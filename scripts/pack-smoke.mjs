import {_electron,expect} from '@playwright/test';
import {mkdtemp,readFile,stat,mkdir,writeFile} from 'node:fs/promises';
import {listPackage,extractFile} from '@electron/asar';
import path from 'node:path';
import os from 'node:os';
const platform=process.platform;
const root=path.resolve(platform==='win32'?'release/win-unpacked':'release/linux-unpacked');
const executablePath=path.join(root,platform==='win32'?'FireCNC Academy.exe':'firecnc-academy');
await stat(executablePath);
const asar=path.join(root,'resources/app.asar'),files=listPackage(asar);
const forbidden=files.filter(f=>/(?:private-keys|license-issuer|\/\.local\/|\/issued\/|\/tests\/fixtures\/|\.(?:pem|fcnclic|pfx|key)$)/i.test(f));
if(forbidden.length)throw new Error('В пакете запрещённые файлы: '+forbidden.join(', '));
const main=extractFile(asar,'dist/desktop/main.cjs').toString();
if(/-----BEGIN (?:ENCRYPTED )?PRIVATE KEY-----/.test(main))throw new Error('Закрытый ключ внутри main bundle.');
const info=JSON.parse(extractFile(asar,'dist/build-info.json').toString());
if(info.development)throw new Error('Для приёмки нужен release-build.');
await stat(path.join(root,`resources/app.asar.unpacked/node_modules/better-sqlite3/prebuilds/${platform}-x64.node`));
const directory=await mkdtemp(path.join(os.tmpdir(),'FireCNC-упаковка-'));
const env={...process.env};delete env.ELECTRON_RUN_AS_NODE;delete env.FCNC_DATA_DIR;
let app;
try {
  app=await _electron.launch({executablePath,args:[`--user-data-dir=${directory}`,...(platform==='linux'?['--ozone-platform=x11']:[])],env,chromiumSandbox:true});
  const actualDirectory=await app.evaluate(({app})=>app.getPath('userData'));
  const normalize=value=>platform==='win32'?path.resolve(value).toLowerCase():path.resolve(value);
  if(normalize(actualDirectory)!==normalize(directory))throw new Error('Пакет не применил изолированный user-data-dir.');
  const page=await app.firstWindow();await page.setViewportSize({width:1366,height:768});
  page.on('pageerror',error=>console.error('Renderer:',error.message));
  await expect(page.getByRole('heading',{name:'От понимания — к обработке'})).toBeVisible();
  await page.context().setOffline(true);await page.reload();
  await expect(page.getByRole('heading',{name:'От понимания — к обработке'})).toBeVisible();
  const state=await page.evaluate(()=>window.academy.state());
  if(!state.ok||state.value.license.status!=='demo')throw new Error('Пустой release должен начинаться в демо.');
  const vector=JSON.parse(await readFile('tests/fixtures/public-license-vector.json','utf8'));
  const rejected=await page.evaluate(token=>window.academy.licenseImport(token),vector.token);
  if(rejected.ok)throw new Error('Release доверяет публичному тестовому ключу.');
  await page.getByRole('button',{name:'Редактор и симулятор',exact:true}).click();
  await page.getByRole('button',{name:'▷ Рассчитать',exact:true}).click();
  await expect(page.getByText('Программа выполнена.',{exact:false})).toBeVisible();
  await page.getByRole('button',{name:'Измерить',exact:true}).click();
  await expect(page.getByText('Ø на Z−15: 30.00 мм',{exact:false})).toBeVisible();
  await page.evaluate(()=>window.scrollTo(0,0));await mkdir('test-results',{recursive:true});
  await page.screenshot({path:`test-results/packaged-${platform}.png`,fullPage:true});
  const report={platform,asarFiles:files.length,development:info.development,trustKeyIds:info.trustKeyIds,privateFiles:false,testVectorTrusted:false,offlineReload:true,turningDiameter:30,runtime:state.value.runtime};
  await writeFile('test-results/packaged-report.json',JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report,null,2));
} finally {await app?.close();}
